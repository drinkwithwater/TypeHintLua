local H = require "goal.support"
H.withTypes(function(manager, node)
	local left = manager:buildInterface(node, {x = manager.type.Integer})
	local right = manager:buildInterface(node, {y = manager.type.String})
	assert(left:intersectAtom(right) == true)
	assert(left:safeIntersect(right) == false)
	assert(left:intersectSome(right) == true)
	local ok, reason = pcall(function() return manager:checkedIntersect(left, right) end)
	assert(not ok and tostring(reason):find("unexpected intersect", 1, true))
	assert(manager.type.Integer:intersectAtom(manager.type.String) == false)
	assert(manager.type.Integer:safeIntersect(manager.type.String) == manager.type.Never)
	assert(manager.type.Integer:safeIntersect(manager:Literal(1)) == manager:Literal(1))
	print("safeIntersect false means non-representable overlap; Never means disjoint")
end)
