local H = require "goal.support"
H.withTypes(function(manager, node)
	local T = manager.type
	local function fn(arg, ret) return manager:checkedFn(arg):Ret(ret) end
	local intFn, strFn = fn(T.Integer, T.Integer), fn(T.String, T.String)
	local third = fn(T.False, T.False)
	local union = manager:checkedUnion(intFn, strFn)
	assert(union:includeAll(intFn) and union:includeAll(strFn))
	assert(union:intersectSome(T.AnyFunction) and T.AnyFunction:intersectSome(union))
	assert(union:safeIntersect(T.AnyFunction) == union)
	assert(not union:intersectSome(third), "Never is not a nonempty intersection")
	assert(union:safeIntersect(third):isNever())
	assert(third:safeIntersect(union):isNever())
	local wideInput, narrowInput = fn(T.Number, T.Integer), fn(T.Integer, T.Number)
	assert(narrowInput:includeAll(wideInput), "parameters are contravariant and results covariant")
	assert(not wideInput:includeAll(narrowInput))
	local any = manager:checkedUnion(T.AnyFunction, intFn, strFn)
	assert(any == T.AnyFunction and any:includeAll(intFn) and any:includeAll(third))
	local open = manager:newNativeOpenFunction()
	assert(manager:checkedUnion(open, T.AnyFunction) == T.AnyFunction)
	assert(manager:checkedUnion(T.AnyFunction, open) == T.AnyFunction)
	local float, text = manager:Literal(1.25), manager:Literal("one")
	assert(manager:checkedUnion(float, float) == float)
	assert(manager:checkedUnion(text, text) == text)
	-- A normalized object singleton must collapse to its atom too.
	local broad = manager:buildInterface(node, {x = T.Integer})
	local narrow = manager:buildInterface(node, {x = T.Integer, y = T.String})
	assert(manager:checkedUnion(broad, narrow) == broad)
	local ok, reason = pcall(function() union:putAwait(third) end)
	assert(not ok and tostring(reason):find("already published", 1, true))
	assert(not union:includeAll(third))
	print("function union emptiness, variance and singleton normalization hold")
end)
